# this tells the python code which libraries of code to load (so we don't have to code *everything* from scratch!)

from matplotlib import pyplot as plt
import numpy as np

# this is the Gdrive folder in which the data is located
infolder='gdrive/'

# run this every time you change the filename or at the beginning of your analysis session

# this is the name of the file you want to analyze
 
filename="data.CSV"

# This reads the data file into some array variables so that we can plot them later

file1 = open(infolder+filename,"r")
file1.readline()    # read the headers

i=0
Time=[]
SQM=[]
Red=[]
Green=[]
Blue=[]
CT=[]
Lux=[]
r=[]
g=[]
b=[]
c=[]
for line in file1:
    ld=line.split(",")
    if len(ld)==11: 
        Time.append(int(ld[0]))
        SQM.append(float(ld[1]))
        Red.append(float(ld[2]))
        Green.append(float(ld[3]))
        Blue.append(float(ld[4]))
        CT.append(int(ld[5]))
        Lux.append(int(ld[6]))
        r.append(int(ld[7]))
        g.append(int(ld[8]))
        b.append(int(ld[9]))
        c.append(int(ld[10]))

#    print(i,ld)
#    if i>100:
#        break
#    i=i+1

Time=np.array(Time)
SQM=np.array(SQM)
Red=np.array(Red)
Green=np.array(Green)
Blue=np.array(Blue)
CT=np.array(CT)
Lux=np.array(Lux)
r=np.array(r)
g=np.array(g)
b=np.array(b)
c=np.array(c)

file1.close()

print("Number of lines in data file:", len(Time))

