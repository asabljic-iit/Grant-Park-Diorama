plt.xlabel('Time (sec)', size = 20)
plt.ylabel('Intensity [mW/m2 (SQM), lux(r,g,b,c)]', size = 20)
# the /1000 turns the milliseconds into seconds
plt.scatter(Time/1000,r,s=0.3,color='red', label = "Red Channel (lux)")   
plt.scatter(Time/1000,g,s=0.3,color='green', label = "Green Channel (lux)")
plt.scatter(Time/1000,b,s=0.3,color='blue', label = "Blue Channel (lux)") 
plt.scatter(Time/1000,c,s=0.3,color='grey', label = "Clear Channel (lux)") 
